CREATE TABLE provider_mapping_decisions (
    decision_id VARCHAR(36) PRIMARY KEY,
    variant_id VARCHAR(60) NOT NULL,
    platform_id VARCHAR(20) NOT NULL,
    retailer_sku VARCHAR(150) NOT NULL,
    revision_no INT NOT NULL CHECK (revision_no > 0),
    disposition VARCHAR(16) NOT NULL CHECK (disposition IN ('APPROVED','REJECTED','UNRESOLVED')),
    reviewed_by VARCHAR(36) NOT NULL,
    reviewed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    source_provider VARCHAR(80) NOT NULL,
    source_record_id VARCHAR(150) NOT NULL,
    evidence_reference VARCHAR(500) NOT NULL,
    evidence_sha256 VARCHAR(64) NOT NULL,
    permission_reference VARCHAR(200) NOT NULL,
    rationale VARCHAR(1000) NOT NULL,
    supersedes_decision_id VARCHAR(36),
    listing_gtin VARCHAR(14),
    listing_brand VARCHAR(100),
    listing_title VARCHAR(150),
    listing_pack VARCHAR(60),
    listing_variant VARCHAR(100),
    listing_formulation VARCHAR(150),
    canonical_gtins TEXT NOT NULL,
    canonical_pack VARCHAR(60) NOT NULL,
    canonical_brand VARCHAR(100) NOT NULL,
    canonical_title VARCHAR(150) NOT NULL,
    canonical_variant VARCHAR(100) NOT NULL,
    blocking_reasons VARCHAR(500) NOT NULL,
    previous_sku VARCHAR(150),
    previous_reviewed_by VARCHAR(36),
    previous_reviewed_at TIMESTAMP NULL,
    UNIQUE (variant_id, platform_id, revision_no),
    FOREIGN KEY (variant_id) REFERENCES product_variants(id),
    FOREIGN KEY (platform_id) REFERENCES grocery_platforms(id),
    FOREIGN KEY (reviewed_by) REFERENCES users(id),
    FOREIGN KEY (supersedes_decision_id) REFERENCES provider_mapping_decisions(decision_id)
);

CREATE INDEX idx_mapping_decision_candidate
    ON provider_mapping_decisions (variant_id, platform_id, retailer_sku, revision_no);
